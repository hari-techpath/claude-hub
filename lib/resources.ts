// ── Helpers ───────────────────────────────────────────────────────────────

export function getByType(type: string) {
  return resources.filter((r) => r.type === type);
}

export function getBySlug(slug: string) {
  return resources.find((r) => r.slug === slug);
}

export function getFeatured() {
  return resources.filter((r) => r.featured);
}

export function getTrending() {
  return [...resources]
    .filter((r) => r.trending)
    .sort((a, b) => b.weeklyViews - a.weeklyViews);
}

export function getHot() {
  return [...resources]
    .filter((r) => r.hot)
    .sort((a, b) => b.weeklyViews - a.weeklyViews);
}

export function getNew() {
  return [...resources].slice().reverse();
}

export function getTop() {
  return [...resources].sort((a, b) => b.stars - a.stars);
}

export function getRelated(resource: Resource, limit = 4) {
  return resources
    .filter(
      (r) =>
        r.id !== resource.id &&
        (r.type === resource.type ||
          r.tags.some((t) => resource.tags.includes(t)))
    )
    .sort((a, b) => b.stars - a.stars)
    .slice(0, limit);
}

export function getCounts() {
  const counts: Record<string, number> = {};
  for (const r of resources) {
    counts[r.type] = (counts[r.type] || 0) + 1;
  }
  return counts;
}

